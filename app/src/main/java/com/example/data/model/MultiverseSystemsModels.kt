@Immutable
data class EssenceResonanceBonuses(
  val damageMult: Float,
  val shieldMult: Float,
  val moveSpeedMult: Float,
  val fireRateMult: Float,
  val cooldownReductionRatio: Float,
  val regenBonusPerSec: Float,
  val lootLuckBonus: Float,
  val summary: String,
  val extendedSourcesSummary: String = "",
  val cooldownHasteBonus: Float = 0f,
) {
  companion object {
    const val MAX_SYNERGY_MAPS: Int = 30

    fun compute(
      blueEssence: Long,
      redEssence: Long,
      yellowEssence: Long,
      greenEssence: Long,
      combinedEssence: Long,
      blastShards: Long,
    ): EssenceResonanceBonuses {
      val bScale = sqrt(blueEssence.coerceAtLeast(0L) / 250f)
      val rScale = sqrt(redEssence.coerceAtLeast(0L) / 150f)
      val yScale = sqrt(yellowEssence.coerceAtLeast(0L) / 150f)
      val gScale = sqrt(greenEssence.coerceAtLeast(0L) / 150f)
      val cScale = sqrt(combinedEssence.coerceAtLeast(0L) / 80f)
      val shardBoost = ln(1f + blastShards.coerceAtLeast(0L) / 5f) * 0.16f

      // Unstuck scaling: base curve + soft diminishing-return tail beyond old hard limits.
      val blueDmg = (bScale * 0.08f).coerceAtMost(1.00f) + ln(1f + (bScale - 12.5f).coerceAtLeast(0f)) * 0.25f
      val redDmg = (rScale * 0.22f).coerceAtMost(3.20f) + ln(1f + (rScale - 14.5f).coerceAtLeast(0f)) * 0.45f
      val combinedDmg = (cScale * 0.35f).coerceAtMost(6.50f) + ln(1f + (cScale - 18.5f).coerceAtLeast(0f)) * 0.70f
      val damageMult = 1.0f + blueDmg + redDmg + combinedDmg + shardBoost

      val blueShd = (bScale * 0.10f).coerceAtMost(1.20f) + ln(1f + (bScale - 12f).coerceAtLeast(0f)) * 0.28f
      val greenShd = (gScale * 0.24f).coerceAtMost(3.40f) + ln(1f + (gScale - 14f).coerceAtLeast(0f)) * 0.48f
      val combinedShd = (cScale * 0.36f).coerceAtMost(6.50f) + ln(1f + (cScale - 18f).coerceAtLeast(0f)) * 0.70f
      val shieldMult = 1.0f + blueShd + greenShd + combinedShd + shardBoost * 0.85f

      val yellowMove = (yScale * 0.12f).coerceAtMost(1.80f) + ln(1f + (yScale - 15f).coerceAtLeast(0f)) * 0.25f
      val blueMove = (bScale * 0.04f).coerceAtMost(0.55f)
      val combinedMove = (cScale * 0.16f).coerceAtMost(2.40f) + ln(1f + (cScale - 15f).coerceAtLeast(0f)) * 0.35f
      val moveSpeedMult = 1.0f + yellowMove + blueMove + combinedMove

      val yellowRate = (yScale * 0.16f).coerceAtMost(2.60f) + ln(1f + (yScale - 16f).coerceAtLeast(0f)) * 0.40f
      val redRate = (rScale * 0.06f).coerceAtMost(0.85f)
      val combinedRate = (cScale * 0.24f).coerceAtMost(3.60f) + ln(1f + (cScale - 15f).coerceAtLeast(0f)) * 0.55f
      val fireRateMult = 1.0f + yellowRate + redRate + combinedRate

      // Uncapped Cooldown Haste: scales monotonically without hitting a hard plateau.
      val hasteBonus = (yScale * 0.08f) + (cScale * 0.14f) + (bScale * 0.03f) + (shardBoost * 0.25f)
      val cooldownReductionRatio = (1f - (1f / (1f + hasteBonus))).coerceIn(0f, 0.99f)

      val regenBonus = ((gScale * 1.4f).coerceAtMost(26f) + (cScale * 2.2f).coerceAtMost(38f))
      val lootLuck = (bScale * 0.05f + cScale * 0.12f).coerceAtMost(3.5f)

      val dmgPct = ((damageMult - 1f) * 100f).toInt()
      val shdPct = ((shieldMult - 1f) * 100f).toInt()
      val spdPct = ((fireRateMult - 1f) * 100f).toInt()
      val hastePct = (hasteBonus * 100f).toInt()
      return EssenceResonanceBonuses(
        damageMult = damageMult,
        shieldMult = shieldMult,
        moveSpeedMult = moveSpeedMult,
        fireRateMult = fireRateMult,
        cooldownReductionRatio = cooldownReductionRatio,
        regenBonusPerSec = regenBonus,
        lootLuckBonus = lootLuck,
        summary = "+${dmgPct}% DMG • +${shdPct}% SHD • +${spdPct}% RATE • +${hastePct}% HASTE",
        cooldownHasteBonus = hasteBonus,
      )
    }

    fun computeComprehensive(
      blueEssence: Long,
      blueEssenceSpent: Long,
      redEssence: Long,
      yellowEssence: Long,
      greenEssence: Long,
      combinedEssence: Long,
      blastShards: Long,
      upgradedMapCount: Int,
      totalMapTierPoints: Int,
      armoryModCount: Int,
      armoryModTotalTiers: Long,
      armoryModTotalPower: Long,
      weaponTierSum: Int,
      weaponStarSum: Int,
      customWeaponCount: Int,
      wonderTierSum: Int,
      gearTierSum: Int,
      gearLevelSum: Int,
      equipmentTierSum: Int,
      skillTierSum: Int,
      outfitTierSum: Int,
      outfitRarityRank: Int,
      perkRankSum: Int,
      blastCoreLevelSum: Int,
      clanLevel: Int,
      ngPlusTier: Int,
      serverDamageMult: Float = 1.0f,
      serverShieldMult: Float = 1.0f,
      serverFireRateMult: Float = 1.0f,
      protectionRankSum: Int = 0,
      perkStarSum: Int = 0,
      customBuffTierSum: Int = 0,
      blastShardTier: Int = 1,
      companionBuffTier: Int = 1,
      crystalsDamagePct: Int = 0,
      crystalsShieldPct: Int = 0,
      crystalsLuckPct: Int = 0,
      magicBonusDmgMult: Float = 1.0f,
      baseShieldBonus: Int = 0,
    ): EssenceResonanceBonuses {
      // Spent Blue Essence preserves and amplifies resonance so upgrading never weakens stats!
      val effectiveBlue = blueEssence.coerceAtLeast(0L) + (blueEssenceSpent.coerceAtLeast(0L) / 2L)
      val base = compute(
        blueEssence = effectiveBlue,
        redEssence = redEssence,
        yellowEssence = yellowEssence,
        greenEssence = greenEssence,
        combinedEssence = combinedEssence,
        blastShards = blastShards,
      )

      val effectiveMaps = upgradedMapCount.coerceIn(0, MAX_SYNERGY_MAPS)
      val mapDmg = (effectiveMaps * 0.045f) + (totalMapTierPoints.coerceAtLeast(0) * 0.008f)
      val mapShd = (effectiveMaps * 0.050f) + (totalMapTierPoints.coerceAtLeast(0) * 0.009f)
      val mapRate = (effectiveMaps * 0.030f) + (totalMapTierPoints.coerceAtLeast(0) * 0.005f)

      val modDmg = (armoryModCount.coerceAtLeast(0) * 0.04f) +
        (armoryModTotalTiers.coerceAtLeast(0L) * 0.025f) +
        sqrt(armoryModTotalPower.coerceAtLeast(0L) / 100f) * 0.14f
      val modShd = (armoryModCount.coerceAtLeast(0) * 0.05f) +
        (armoryModTotalTiers.coerceAtLeast(0L) * 0.030f) +
        sqrt(armoryModTotalPower.coerceAtLeast(0L) / 100f) * 0.15f
      val modRate = (armoryModCount.coerceAtLeast(0) * 0.025f) +
        (armoryModTotalTiers.coerceAtLeast(0L) * 0.018f) +
        sqrt(armoryModTotalPower.coerceAtLeast(0L) / 140f) * 0.10f

      val shardTierAbove = (blastShardTier - 1).coerceAtLeast(0)
      val companionTierAbove = (companionBuffTier - 1).coerceAtLeast(0)
      val globalPerkSynergy = 1f + (perkRankSum * 0.015f) + (perkStarSum * 0.03f)
      val crystalDmgFrac = crystalsDamagePct.coerceAtLeast(0) / 100f
      val crystalShdFrac = crystalsShieldPct.coerceAtLeast(0) / 100f
      val crystalLuckFrac = crystalsLuckPct.coerceAtLeast(0) / 100f
      val baseShdFrac = baseShieldBonus.coerceAtLeast(0) / 150f

      val arsenalDmg = (weaponTierSum * 0.03f) + (weaponStarSum * 0.035f) + (customWeaponCount * 0.08f) + (wonderTierSum * 0.025f)
      val gearShd = (gearTierSum * 0.045f) + (gearLevelSum * 0.008f) + (equipmentTierSum * 0.035f) +
        (outfitTierSum * 0.02f) + (outfitRarityRank * 0.09f) + (protectionRankSum * 0.04f) + (customBuffTierSum * 0.035f)
      val skillRate = (skillTierSum * 0.020f) + (equipmentTierSum * 0.022f) +
        (perkRankSum * 0.026f * globalPerkSynergy) + (blastCoreLevelSum * 0.025f) + (companionTierAbove * 0.03f)
      val clanAndNgBonus = (clanLevel * 0.03f) + (ngPlusTier * 0.12f) + (shardTierAbove * 0.05f)

      val finalDmg = (base.damageMult + mapDmg + modDmg + arsenalDmg + (perkRankSum * 0.024f * globalPerkSynergy) +
        (perkStarSum * 0.04f) + (blastCoreLevelSum * 0.03f) + (customBuffTierSum * 0.03f) + clanAndNgBonus + crystalDmgFrac) *
        serverDamageMult * magicBonusDmgMult.coerceAtLeast(1f)
      val finalShd = (base.shieldMult + mapShd + modShd + gearShd + (perkRankSum * 0.028f * globalPerkSynergy) +
        (perkStarSum * 0.04f) + (blastCoreLevelSum * 0.03f) + clanAndNgBonus + crystalShdFrac + baseShdFrac) * serverShieldMult
      val finalRate = (base.fireRateMult + mapRate + modRate + skillRate + (customWeaponCount * 0.05f) +
        (customBuffTierSum * 0.025f) + (shardTierAbove * 0.03f) + (crystalDmgFrac * 0.35f)) * serverFireRateMult
      val finalMove = base.moveSpeedMult + (effectiveMaps * 0.015f) + (armoryModTotalTiers * 0.006f) +
        (perkRankSum * 0.014f * globalPerkSynergy) + (protectionRankSum * 0.008f) + (companionTierAbove * 0.015f) + (crystalLuckFrac * 0.25f)

      // Uncapped cumulative Cooldown Haste across all upgrades, skills, perks, gear, maps, crystals, and essences
      val totalHaste = base.cooldownHasteBonus +
        (effectiveMaps * 0.018f) +
        (skillTierSum * 0.022f) +
        (armoryModTotalTiers * 0.010f) +
        (equipmentTierSum * 0.020f) +
        (gearTierSum * 0.015f) +
        (perkRankSum * 0.018f * globalPerkSynergy) +
        (perkStarSum * 0.03f) +
        (protectionRankSum * 0.015f) +
        (customBuffTierSum * 0.025f) +
        (blastCoreLevelSum * 0.022f) +
        (shardTierAbove * 0.03f) +
        (companionTierAbove * 0.025f) +
        (crystalLuckFrac * 0.45f)
      val extraCdr = (1f - (1f / (1f + totalHaste))).coerceIn(0f, 0.99f)
      val finalRegen = base.regenBonusPerSec + (effectiveMaps * 0.45f) + (gearTierSum * 0.35f) +
        (perkRankSum * 0.55f * globalPerkSynergy) + (protectionRankSum * 0.4f) + (customBuffTierSum * 0.4f) + (crystalShdFrac * 3.5f)
      val finalLuck = base.lootLuckBonus + (effectiveMaps * 0.04f) + (armoryModCount * 0.03f) + (shardTierAbove * 0.05f) + crystalLuckFrac

      val dmgPct = ((finalDmg - 1f) * 100f).toInt()
      val shdPct = ((finalShd - 1f) * 100f).toInt()
      val spdPct = ((finalRate - 1f) * 100f).toInt()
      val hastePct = (totalHaste * 100f).toInt()
      return EssenceResonanceBonuses(
        damageMult = finalDmg,
        shieldMult = finalShd,
        moveSpeedMult = finalMove,
        fireRateMult = finalRate,
        cooldownReductionRatio = extraCdr,
        regenBonusPerSec = finalRegen,
        lootLuckBonus = finalLuck,
        summary = "+${dmgPct}% DMG • +${shdPct}% SHD • +${spdPct}% RATE • +${hastePct}% HASTE",
        extendedSourcesSummary = "Sources: Essences + ${blueEssenceSpent} Spent • $effectiveMaps/$MAX_SYNERGY_MAPS Maps • $armoryModCount Mods • Crystals(+${crystalsDamagePct}%/+${crystalsShieldPct}%) • Perks(x${String.format(java.util.Locale.US, "%.2f", globalPerkSynergy)}) • Prot($protectionRankSum) • Custom($customBuffTierSum)",
        cooldownHasteBonus = totalHaste,
      )
    }
  }
}

